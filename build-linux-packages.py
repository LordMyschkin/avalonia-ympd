#!/usr/bin/env python3
"""Cross-build self-contained x86_64 Debian and Arch Linux packages."""

import gzip
import hashlib
import io
import os
import subprocess
import tarfile
import tempfile
import time
import xml.etree.ElementTree as ET
from pathlib import Path


ROOT = Path(__file__).resolve().parent
PROJECT = ROOT / "ModernYmpd" / "ModernYmpd.csproj"
DIST = ROOT / "dist"
VERSION = ET.parse(PROJECT).getroot().findtext("PropertyGroup/Version")
if not VERSION:
    raise SystemExit("Project version is missing")
BUILD_DATE = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))
DESCRIPTION = "MPD desktop player with random library queue filling"
HOMEPAGE = "https://github.com/LordMyschkin/avalonia-ympd"
DEBIAN_DEPENDS = (
    "ca-certificates, libc6, libgcc-s1, libgssapi-krb5-2, libicu76, "
    "libssl3t64, libstdc++6, tzdata, libx11-6, libice6, libsm6, libfontconfig1"
)
ARCH_DEPENDS = (
    "ca-certificates", "glibc", "gcc-libs", "krb5", "icu", "openssl",
    "tzdata", "libx11", "libice", "libsm", "fontconfig",
)


def run(*command):
    print("+", " ".join(map(str, command)), flush=True)
    subprocess.run(command, check=True, cwd=ROOT)


def contents(publish):
    files = {}
    for source in sorted(publish.rglob("*")):
        if source.is_file():
            target = "opt/a-mpd/" + source.relative_to(publish).as_posix()
            files[target] = (source.read_bytes(), source.stat().st_mode & 0o777)
    if "opt/a-mpd/ModernYmpd" not in files:
        raise RuntimeError("The Linux apphost was not published")
    files["usr/bin/a-mpd"] = (
        b'#!/bin/sh\nexec /opt/a-mpd/ModernYmpd "$@"\n', 0o755
    )
    files["usr/share/applications/a-mpd.desktop"] = (
        b"[Desktop Entry]\nType=Application\nName=A-mpd\n"
        b"Comment=MPD desktop player with library shuffle\n"
        b"Exec=a-mpd\nIcon=a-mpd\nTerminal=false\n"
        b"Categories=AudioVideo;Audio;Player;\n"
        b"Keywords=MPD;Music;Playlist;\n", 0o644
    )
    files["usr/share/icons/hicolor/scalable/apps/a-mpd.svg"] = (
        (ROOT / "ModernYmpd/Assets/app-icon.svg").read_bytes(), 0o644
    )
    files["usr/share/licenses/a-mpd/LICENSE"] = (
        (ROOT / "LICENSE").read_bytes(), 0o644
    )
    return files


def tar_bytes(files):
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode="w", format=tarfile.GNU_FORMAT) as archive:
        directories = set()
        for name in files:
            parent = Path(name).parent
            while str(parent) != ".":
                directories.add(parent.as_posix())
                parent = parent.parent
        for name in sorted(directories, key=lambda item: (item.count("/"), item)):
            info = tarfile.TarInfo(name + "/")
            info.type = tarfile.DIRTYPE
            info.mode = 0o755
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mtime = BUILD_DATE
            archive.addfile(info)
        for name, (data, mode) in files.items():
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = mode
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mtime = BUILD_DATE
            archive.addfile(info, io.BytesIO(data))
    return output.getvalue()


def ar_member(name, data):
    header = (
        f"{name:<16}{BUILD_DATE:<12}{0:<6}{0:<6}"
        f"{'100644':<8}{len(data):<10}`\n"
    ).encode("ascii")
    if len(header) != 60:
        raise RuntimeError("Invalid ar header")
    return header + data + (b"\n" if len(data) % 2 else b"")


def build_deb(files):
    installed_kib = (sum(len(data) for data, _ in files.values()) + 1023) // 1024
    control = (
        "Package: a-mpd\n"
        f"Version: {VERSION}\n"
        "Section: sound\n"
        "Priority: optional\n"
        "Architecture: amd64\n"
        "Maintainer: A-mpd Project <noreply@github.com>\n"
        f"Installed-Size: {installed_kib}\n"
        f"Depends: {DEBIAN_DEPENDS}\n"
        f"Homepage: {HOMEPAGE}\n"
        f"Description: {DESCRIPTION}\n"
        " Standalone Avalonia client that controls MPD directly.\n"
    ).encode()
    data = b"!<arch>\n"
    data += ar_member("debian-binary", b"2.0\n")
    data += ar_member("control.tar.gz", gzip.compress(tar_bytes({"control": (control, 0o644)}), mtime=0))
    data += ar_member("data.tar.gz", gzip.compress(tar_bytes(files), mtime=0))
    destination = DIST / f"a-mpd_{VERSION}_amd64.deb"
    destination.write_bytes(data)
    print("Built:", destination, flush=True)


def build_arch(files):
    installed_size = sum(len(data) for data, _ in files.values())
    pkginfo = (
        "# Generated by build-linux-packages.py\n"
        "pkgname = a-mpd\n"
        "pkgbase = a-mpd\n"
        f"pkgver = {VERSION}-1\n"
        f"pkgdesc = {DESCRIPTION}\n"
        f"url = {HOMEPAGE}\n"
        f"builddate = {BUILD_DATE}\n"
        "packager = A-mpd Project <noreply@github.com>\n"
        f"size = {installed_size}\n"
        "arch = x86_64\n"
        "license = GPL-2.0-only\n"
        + "".join(f"depend = {dependency}\n" for dependency in ARCH_DEPENDS)
    ).encode()
    payload = {".PKGINFO": (pkginfo, 0o644), **files}
    mtree = ["#mtree", "/set type=file uid=0 gid=0 mode=0644"]
    directories = set()
    for name in payload:
        parent = Path(name).parent
        while str(parent) != ".":
            directories.add(parent.as_posix())
            parent = parent.parent
    for name in sorted(directories, key=lambda item: (item.count("/"), item)):
        mtree.append(f"./{name} type=dir mode=0755 time={BUILD_DATE}.0")
    for name, (data, mode) in payload.items():
        mtree.append(
            f"./{name} mode=0{mode:o} time={BUILD_DATE}.0 size={len(data)} "
            f"sha256digest={hashlib.sha256(data).hexdigest()}"
        )
    payload = {
        ".MTREE": (gzip.compress(("\n".join(mtree) + "\n").encode(), mtime=0), 0o644),
        **payload,
    }
    destination = DIST / f"a-mpd-{VERSION}-1-x86_64.pkg.tar.zst"
    archive = tar_bytes(payload)
    subprocess.run(["zstd", "-q", "-19", "-f", "-o", str(destination)],
                   input=archive, check=True)
    print("Built:", destination, flush=True)


def main():
    DIST.mkdir(exist_ok=True)
    dotnet = os.environ.get("DOTNET", "dotnet")
    with tempfile.TemporaryDirectory(prefix="a-mpd-linux-") as temporary:
        publish = Path(temporary) / "publish"
        run(dotnet, "restore", str(PROJECT), "-r", "linux-x64",
            "--source", "https://api.nuget.org/v3/index.json")
        run(dotnet, "publish", str(PROJECT), "-c", "Release", "-r", "linux-x64",
            "--self-contained", "true", "--no-restore", "-o", str(publish),
            "-p:PublishSingleFile=true", "-p:IncludeNativeLibrariesForSelfExtract=true",
            "-p:EnableCompressionInSingleFile=true", "-p:DebugType=none",
            "-p:DebugSymbols=false")
        files = contents(publish)
        build_deb(files)
        build_arch(files)


if __name__ == "__main__":
    main()
